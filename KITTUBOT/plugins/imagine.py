"""
🎨 KITTUBOT Autonomous AI Image Generation Engine
Supports explicit commands (/imagine, /draw) and conversational requests
(e.g. 'cat ki photo bana de').
"""

import urllib.parse
import httpx
from telegram import Update
from telegram.ext import Application, CommandHandler, ContextTypes
from KITTUBOT.config import config
from KITTUBOT import log

__mod_name__ = "Imagine"
__help__ = """
<blockquote>🎨 <b>AI Image Generation:</b>
• <code>/imagine [prompt]</code> - Generate ultra high-res AI artwork
• <code>/draw [prompt]</code> - Quick alias for image generation
• <b>Natural language:</b> Just say <i>"a cute puppy running in rain ki photo bana de"</i></blockquote>
"""


async def fetch_ai_image(prompt: str) -> bytes | None:
    """Fetches high-res AI generated image using Pollinations / OpenAI."""
    # 1. Primary engine: Pollinations AI (Instant, uncapped, beautiful high quality)
    encoded = urllib.parse.quote_plus(prompt)
    url = f"https://image.pollinations.ai/prompt/{encoded}?width=1024&height=1024&nologo=true&enhance=true"

    try:
        async with httpx.AsyncClient(timeout=35.0, follow_redirects=True) as client:
            res = await client.get(url)
            if res.status_code == 200 and len(res.content) > 5000:
                return res.content
    except Exception as e:
        log.warning(f"[Imagine] Pollinations AI fetch error: {e}")

    # 2. Fallback to OpenAI DALL-E if key is available
    if config.OPENAI_API_KEY:
        try:
            async with httpx.AsyncClient(timeout=30.0) as client:
                res = await client.post(
                    "https://api.openai.com/v1/images/generations",
                    headers={
                        "Authorization": f"Bearer {config.OPENAI_API_KEY}",
                        "Content-Type": "application/json",
                    },
                    json={
                        "prompt": prompt,
                        "n": 1,
                        "size": "1024x1024",
                    },
                )
                if res.status_code == 200:
                    data = res.json()
                    img_url = data["data"][0]["url"]
                    dl_res = await client.get(img_url)
                    if dl_res.status_code == 200:
                        return dl_res.content
        except Exception as e:
            log.warning(f"[Imagine] OpenAI DALL-E fetch error: {e}")

    return None


async def generate_and_reply_image(update: Update, context: ContextTypes.DEFAULT_TYPE, prompt: str):
    """Core image generator used by both commands and natural conversational triggers."""
    message = update.effective_message
    chat = update.effective_chat
    if not message or not prompt:
        return

    try:
        await context.bot.send_chat_action(chat_id=chat.id, action="upload_photo")
    except Exception:
        pass

    status_msg = None
    try:
        status_msg = await message.reply_text("🎨 painting your idea... give me a sec ✨")
    except Exception:
        pass

    img_bytes = await fetch_ai_image(prompt)

    if not img_bytes:
        if status_msg:
            try:
                await status_msg.edit_text("ugh couldn't draw that... try another prompt? 🥺")
            except Exception:
                pass
        return

    caption = (
        f"🎨 <b>Prompt:</b> <i>{prompt}</i>\n"
        f"✨ <i>Generated by Kittu</i>"
    )

    try:
        await message.reply_photo(
            photo=img_bytes,
            caption=caption,
            parse_mode="HTML",
        )
        if status_msg:
            await status_msg.delete()
    except Exception as e:
        log.warning(f"[Imagine] Failed to send photo: {e}")
        if status_msg:
            try:
                await status_msg.edit_text("Failed to send generated image.")
            except Exception:
                pass


async def imagine_command(update: Update, context: ContextTypes.DEFAULT_TYPE):
    """Handler for /imagine and /draw."""
    message = update.effective_message
    if not message:
        return

    if not context.args:
        await message.reply_html(
            "🎨 <b>Give me a prompt to draw!</b>\n"
            "• <code>/imagine a cute neon cat drinking iced coffee in mumbai</code>\n"
            "• Or just say: <i>'cyberpunk warrior ki photo bana de'</i>"
        )
        return

    prompt = " ".join(context.args).strip()
    await generate_and_reply_image(update, context, prompt)


def register_handlers(app: Application):
    app.add_handler(CommandHandler(["imagine", "draw"], imagine_command))
